export const formatReviewCount = (count: number) => {
  const lastTwo = count % 100;
  const lastOne = count % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return `${count} отзывов`;
  if (lastOne === 1) return `${count} отзыв`;
  if (lastOne >= 2 && lastOne <= 4) return `${count} отзыва`;
  return `${count} отзывов`;
};

export const getPartnerReviews = (makerId?: string) =>
  makerId ? PARTNER_REVIEWS[makerId] ?? [] : [];

export const getPartnerReviewSummary = (makerId?: string) => {
  const reviews = getPartnerReviews(makerId);
  const totalCount = reviews.length;

  if (reviews.length === 0 || totalCount === 0) {
    return {
      rating: 0,
      reviewsLabel: "отзывов пока нет",
      totalCount: 0,
      hasReviews: false,
    };
  }

  const rating = reviews.reduce((sum, review) => sum + review.stars, 0) / reviews.length;
  return {
    rating,
    reviewsLabel: formatReviewCount(totalCount),
    totalCount,
    hasReviews: true,
  };
};
