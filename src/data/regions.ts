export const regionGroups: RegionGroup[] = deliveryRegionSeeds.map((seed) => {
  const baseRegion = regions.find((region) => region.slug === seed.baseRegionSlug);
  if (!baseRegion) throw new Error(`Не найден базовый регион ${seed.baseRegionSlug}`);

  return {
    slug: seed.baseRegionSlug,
    label: seed.label,
    region: baseRegion,
    cities: [
      baseRegion,
      ...(seed.area ? [makeDeliveryAreaRegion(baseRegion, seed.area)] : []),
      ...seed.cities.map((city) => makeDeliveryCityRegion(baseRegion, city)),
    ],
  };
});

export const allRegions = regionGroups.flatMap((group) => group.cities);

