import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { createServer } from "vite";

const args = new Set(process.argv.slice(2));
const checkOnly = args.has("--check");
const auditPath = "outputs/manufacturer-source-audit.json";
const outputPath = "src/data/generatedProjectMedia.ts";
const reportPath = "outputs/project-media-sync-report.json";
const MAX_GALLERY_SIZE = 10;

const canonicalMediaKey = (url) => {
  try {
    const parsed = new URL(url);
    const tildaAsset = parsed.pathname.match(/\/(tild[a-z0-9-]+)\/(?:-\/[^/]+\/)*([^/]+)$/iu);
    return tildaAsset ? `${tildaAsset[1]}/${tildaAsset[2]}` : `${parsed.host}${parsed.pathname}`;
  } catch {
    return url;
  }
};

const hasRejectedMediaName = (url) => {
  if (!url) return true;
  let pathname = url;
  try {
    const parsed = new URL(url);
    pathname = decodeURIComponent(`${parsed.host}${parsed.pathname}`);
  } catch {
    pathname = decodeURIComponent(url);
  }
  if (/\.(?:js|css|mjs|map|svg|gif|mp4|webm)$/iu.test(pathname)) return true;
  return /(?:logo|favicon|icon|(?:^|[\/_-])icn|avatar|promocode|promo[_-]|empty|payment|captcha|qr[_-]|social|youtube|rutube|looo)/iu.test(pathname);
};

const isRejectedMedia = hasRejectedMediaName;

const isPlan = (url) => /(?:^|[\/_-])(plan|planirov|floorplan|layout|план)/iu.test(decodeURIComponent(url));

const formatManifest = ({ entries, auditGeneratedAt }) => `/**
 * Generated by scripts/sync-project-media.mjs from official project pages.
 * Do not edit individual projects here; rerun the synchronizer instead.
 */
export type GeneratedProjectMediaItem = Readonly<{
  image: string;
  type: "photo" | "plan";
  fit?: "cover" | "contain";
}>;

export const generatedProjectMedia: Readonly<Record<number, readonly GeneratedProjectMediaItem[]>> = ${JSON.stringify(entries, null, 2)};

export const generatedProjectMediaMeta = ${JSON.stringify({
    generatedAt: new Date().toISOString(),
    sourceAuditGeneratedAt: auditGeneratedAt,
    projectCount: Object.keys(entries).length,
  }, null, 2)} as const;
`;

const audit = JSON.parse(await readFile(auditPath, "utf8"));
const vite = await createServer({ appType: "custom", logLevel: "error", server: { middlewareMode: true } });

try {
  const { projectRecords } = await vite.ssrLoadModule("/src/data/projects.ts");
  const { generatedProjectMedia: previousManifest } = await vite.ssrLoadModule("/src/data/generatedProjectMedia.ts");
  const projectById = new Map(projectRecords.map((project) => [project.id, project]));
  const entries = {};
  const summary = { projects: 0, imported: 0, unchanged: 0, blocked: 0, rejectedCommon: 0 };

  for (const manufacturer of audit.manufacturers) {
    const pageCount = manufacturer.projects.length;
    const frequency = new Map();
    for (const sourceProject of manufacturer.projects) {
      const keys = new Set((sourceProject.source?.media?.imageUrls ?? []).map(canonicalMediaKey));
      for (const key of keys) frequency.set(key, (frequency.get(key) ?? 0) + 1);
    }
    const commonThreshold = Math.max(3, Math.ceil(pageCount * 0.35));

    for (const sourceProject of manufacturer.projects) {
      summary.projects += 1;
      const project = projectById.get(sourceProject.id);
      if (!project || !sourceProject.source?.media) {
        summary.blocked += 1;
        if (previousManifest[sourceProject.id]?.length) entries[sourceProject.id] = previousManifest[sourceProject.id];
        continue;
      }

      const seen = new Set();
      const candidates = [];
      for (const url of sourceProject.source.media.imageUrls) {
        const key = canonicalMediaKey(url);
        if (seen.has(key) || isRejectedMedia(url)) continue;
        seen.add(key);
        if ((frequency.get(key) ?? 0) >= commonThreshold) {
          summary.rejectedCommon += 1;
          continue;
        }
        candidates.push(url);
      }

      const selected = candidates.slice(0, MAX_GALLERY_SIZE).map((image) => ({
        image,
        type: isPlan(image) ? "plan" : "photo",
        ...(isPlan(image) ? { fit: "contain" } : {}),
      }));
      const currentFirstKey = canonicalMediaKey(project.gallery[0]?.image ?? "");
      const currentFirstFrequency = manufacturer.projects.filter((item) => {
        const local = projectById.get(item.id);
        return canonicalMediaKey(local?.gallery[0]?.image ?? "") === currentFirstKey;
      }).length;
      const currentLooksLikeFallback = hasRejectedMediaName(project.gallery[0]?.image ?? "")
        || (currentFirstFrequency >= commonThreshold && project.gallery.length === 1);
      const currentHasPlan = project.gallery.some((item) => item.type === "plan");
      const selectedHasPlan = selected.some((item) => item.type === "plan");
      const improvesCoverage = selected.length >= 2
        && selected.length > project.gallery.length
        && (!currentHasPlan || selectedHasPlan);

      if (selected.length > 0 && (currentLooksLikeFallback || improvesCoverage)) {
        entries[project.id] = selected;
        summary.imported += 1;
      } else {
        summary.unchanged += 1;
      }
    }
  }

  const auditedIds = new Set(audit.manufacturers.flatMap((manufacturer) => manufacturer.projects.map((project) => project.id)));
  const finalGalleries = projectRecords
    .filter((project) => auditedIds.has(project.id))
    .map((project) => ({ project, gallery: entries[project.id] ?? project.gallery }));
  const oneImageProjects = finalGalleries
    .filter(({ gallery }) => gallery.length === 1)
    .map(({ project, gallery }) => ({ id: project.id, manufacturerId: project.manufacturerId, name: project.name, image: gallery[0]?.image ?? null }));
  const zeroImageProjects = finalGalleries
    .filter(({ gallery }) => gallery.length === 0)
    .map(({ project }) => ({ id: project.id, manufacturerId: project.manufacturerId, name: project.name }));
  const suspiciousFirstImageProjects = finalGalleries
    .filter(({ gallery }) => hasRejectedMediaName(gallery[0]?.image ?? ""))
    .map(({ project, gallery }) => ({ id: project.id, manufacturerId: project.manufacturerId, name: project.name, image: gallery[0]?.image ?? null }));
  summary.oneImage = oneImageProjects.length;
  summary.zeroImages = zeroImageProjects.length;
  summary.suspiciousFirstImages = suspiciousFirstImageProjects.length;

  const output = formatManifest({ entries, auditGeneratedAt: audit.generatedAt });
  if (checkOnly) {
    const current = await readFile(outputPath, "utf8");
    const normalizedCurrent = current.replace(/"generatedAt": "[^"]+"/u, '"generatedAt": "<timestamp>"');
    const normalizedOutput = output.replace(/"generatedAt": "[^"]+"/u, '"generatedAt": "<timestamp>"');
    if (normalizedCurrent !== normalizedOutput) {
      console.error("Медиаманифест устарел. Запустите npm run manufacturer:sync-media.");
      process.exitCode = 1;
    }
  } else {
    await writeFile(outputPath, output, "utf8");
    await writeFile(reportPath, `${JSON.stringify({
      generatedAt: new Date().toISOString(),
      sourceAuditGeneratedAt: audit.generatedAt,
      summary,
      oneImageProjects,
      zeroImageProjects,
      suspiciousFirstImageProjects,
    }, null, 2)}\n`, "utf8");
  }
  console.log(JSON.stringify(summary, null, 2));
} finally {
  await vite.close();
}
